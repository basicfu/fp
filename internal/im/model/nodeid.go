package model

import (
	"fmt"
	"time"
)

// NewNodeID 生成 "主机标识-进程号-启动毫秒时间戳"。每次启动都是新节点，
// 这样重启后旧条目会被当成死节点过滤，而不是被误认为仍然有效。
//
// 光有主机名加毫秒时间戳不够：同一台机器上同一毫秒启动的两个进程会算出
// 完全相同的节点标识，而这不是理论上的小概率事件——本地开发、单机双
// 节点的预发环境、进程管理器并行拉起多实例、单机多进程吃满多核，都是
// 会真的撞上的场景。撞了之后服务表/存活表两个进程交替写同一个字段，
// 服务可见性来回抖动，client 发上来的消息被静默丢弃，判死也会因为一个
// 死进程的字段被另一个活进程的心跳续期而失效，10 秒的判死承诺变成
// conn 元数据 30 分钟的过期兜底才生效。
//
// 拼上进程号后，同主机的并发进程号一定互异（同一时刻不可能有两个进程
// 共用同一个 pid），彻底堵住"同机同毫秒"这条碰撞路径；时间戳继续覆盖
// "同一进程号跨重启复用"这条路径（pid 会被操作系统回收再分配给后来的
// 新进程）——两者叠加才是完备的，少一个都不够：只有 pid 没有时间戳，
// 进程重启后 pid 复用会撞上一个理论仍然存活、只是心跳已经停摆的旧节点；
// 只有时间戳没有 pid 就是本函数原来的样子，问题正是它引出的。
//
// 签名保持纯函数（pid 由调用方传入，不在这里读 os.Getpid()），是为了
// 可测试性：NewNodeID 本身不需要也不应该有任何全局状态或副作用。
//
// 节点标识在全仓从没有任何地方对它做过切分/解析（只作为整体字符串
// 存取、比较），所以格式可以自由改，不用担心破坏已有的解析逻辑。
func NewNodeID(host string, pid int, now time.Time) string {
	return fmt.Sprintf("%s-%d-%d", host, pid, now.UnixMilli())
}
